#!/bin/bash
set -e

echo "========================================================"
echo "  Git Commit and Push (НПФ «АМК Горизонт»)"
echo "========================================================"

MSG="$1"
if [ -z "$MSG" ]; then
    read -r -p "Введите сообщение коммита: " MSG
fi

if [ -z "$MSG" ]; then
    echo "[ОШИБКА] Сообщение коммита не может быть пустым!"
    exit 1
fi

echo ""
echo "[1/3] Добавление файлов в индекс (git add -A)..."
git add -A

echo ""
echo "[2/3] Создание локального коммита (git commit)..."
git commit -m "$MSG" || echo "[ПРЕДУПРЕЖДЕНИЕ] Нет изменений для коммита или ошибка."

echo ""
echo "[3/3] Отправка в удаленный репозиторий (git push origin main)..."
git push origin main

echo ""
echo "========================================================"
echo "  Успешно закоммичено и отправлено в репозиторий!"
echo "========================================================"
